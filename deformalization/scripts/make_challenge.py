#!/usr/bin/env python3
"""Generate Challenge.lean, Challenge/*.lean and comparator.json from the GroupoidCorr sources.

Challenge/<File>.lean is GroupoidCorr/<File>.lean with every theorem's proof replaced by `sorry`:
definitions, instances and structures are copied verbatim (with the proofs they contain), in the
same module structure, so that they are identical to the library's. Every theorem is a
`lake comparator` target: its statement must match the library's exactly, and the library's
proof may use only the permitted axioms.

Run from the project root:  python3 scripts/make_challenge.py
Then:                        lake comparator      (reads comparator.json)
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ORDER = [l.split()[-1] for l in (ROOT / "GroupoidCorr.lean").read_text().splitlines()
         if l.startswith(("import ", "public import "))]
AXIOMS = ["propext", "Quot.sound", "Classical.choice"]

ROOT_DOC = '''module

{imports}

/-!
# GroupoidCorr: the challenge

Generated by `scripts/make_challenge.py` from `GroupoidCorr/*.lean`; do not edit by hand.

`Challenge/<File>.lean` is `GroupoidCorr/<File>.lean` with every theorem's proof replaced by
`sorry` and `GroupoidCorr.*` imports redirected to `Challenge.*`. Definitions, instances and
structures are copied verbatim, in the same module structure, so that they are identical to the
library's (down to the names of auxiliary proof lemmas). The challenge imports only Mathlib:
read it to know exactly what is proved.

`lake comparator` (configuration `comparator.json`; solution module `Solution`, which imports
the library) checks that every theorem here is proved, with the same statement, by the library,
using only the axioms `propext`, `Quot.sound`, `Classical.choice`, and that the proofs are
accepted by the kernel.
-/
'''

FILE_NOTE = ("-- Generated by scripts/make_challenge.py from {src}; do not edit by hand.\n"
             "-- Every theorem's proof is `sorry` by design; do not warn about it.\n"
             "set_option warn.sorry false\n")

TOP = re.compile(r"^\S")  # a line starting at column 0 begins a new top-level item
BINDER = re.compile(r"\b(haveI|letI|let|have)\b[^;]*$")  # an open `have x :=` on this line


def strip_proofs(src: str):
    """Replace the proof of every top-level `theorem`/`lemma` by `sorry`; collect full names."""
    lines = src.splitlines()
    out, names, ns = [], [], []
    i = 0
    while i < len(lines):
        line = lines[i]
        m_ns = re.match(r"^namespace\s+(\S+)", line)
        m_end = re.match(r"^end\s+(\S+)", line)
        if m_ns:
            ns.append(m_ns.group(1))
        elif m_end and ns and ns[-1] == m_end.group(1):
            ns.pop()
        m = re.match(r"^(theorem|lemma)\s+(\S+)", line)
        if not m:
            out.append(line)
            i += 1
            continue
        names.append(".".join(ns + [m.group(2)]))
        # find where the proof starts: the first `:=` at bracket depth 0 that does not belong to
        # a `haveI`/`letI`/`let`/`have` inside the statement, or a line-final `where`
        depth, j, buf = 0, i, []
        found = None
        while j < len(lines) and found is None:
            text = lines[j]
            k = 0
            while k < len(text):
                c = text[k]
                if c in "([{⟨":
                    depth += 1
                elif c in ")]}⟩":
                    depth -= 1
                elif depth == 0 and text.startswith(":=", k) and not BINDER.search(text[:k]):
                    found = (j, k)
                    break
                elif (depth == 0 and text.startswith("where", k) and text[k + 5:].strip() == ""
                      and (k == 0 or text[k - 1] == " ")):
                    found = (j, k)
                    break
                k += 1
            if found is None:
                buf.append(text)
                j += 1
        j, k = found
        buf.append(lines[j][:k].rstrip() + " := by")
        out.extend(buf)
        out.append("  sorry")
        # skip the rest of the proof: indented lines (and blank lines) up to the next top item
        j += 1
        while j < len(lines) and (lines[j].strip() == "" or not TOP.match(lines[j])):
            j += 1
        out.append("")
        i = j
    return "\n".join(out), names


def main():
    theorems = []
    outdir = ROOT / "Challenge"
    outdir.mkdir(exist_ok=True)
    for old in outdir.glob("*.lean"):
        old.unlink()
    for mod in ORDER:
        path = ROOT / (mod.replace(".", "/") + ".lean")
        src = path.read_text(encoding="utf-8")
        src = re.sub(r"^((?:public )?import )GroupoidCorr\.", r"\1Challenge.", src, flags=re.M)
        body, names = strip_proofs(src)
        theorems += names
        lines = body.splitlines()
        last_import = max(i for i, l in enumerate(lines) if l.startswith(("import ", "public import ")))
        note = FILE_NOTE.format(src=path.relative_to(ROOT))
        lines.insert(last_import + 1, "\n" + note.rstrip("\n"))
        (outdir / path.name).write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    imports = "\n".join("public import " + m.replace("GroupoidCorr.", "Challenge.") for m in ORDER)
    (ROOT / "Challenge.lean").write_text(ROOT_DOC.format(imports=imports), encoding="utf-8")
    config = {
        "challenge_module": "Challenge",
        "solution_module": "Solution",
        "theorem_names": theorems,
        "definition_names": [],
        "permitted_axioms": AXIOMS,
    }
    (ROOT / "comparator.json").write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    print(f"Challenge/: {len(ORDER)} modules, {len(theorems)} theorems; comparator.json written")


if __name__ == "__main__":
    main()
